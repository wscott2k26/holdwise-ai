const ACADEMY_OVERRIDE_KEY = "holdwise_academy_overrides_v1";

function readOverrides() {
  if (typeof localStorage === "undefined") return {};
  try { return JSON.parse(localStorage.getItem(ACADEMY_OVERRIDE_KEY) || "{}"); } catch { return {}; }
}

export function saveAcademyOverride(gameId, patch) {
  if (typeof localStorage === "undefined") return;
  const overrides = readOverrides();
  overrides[gameId] = { ...(overrides[gameId] || {}), ...patch, updatedAt: new Date().toISOString() };
  localStorage.setItem(ACADEMY_OVERRIDE_KEY, JSON.stringify(overrides));
}

export function clearAcademyOverride(gameId) {
  if (typeof localStorage === "undefined") return;
  const overrides = readOverrides();
  delete overrides[gameId];
  localStorage.setItem(ACADEMY_OVERRIDE_KEY, JSON.stringify(overrides));
}

export function gameContent(id) {
  const content = COURSE_CONTENT[id];
  if (!content) return null;
  const override = readOverrides()[id] || {};
  return structuredCloneSafe({ ...content, ...override });
}

function structuredCloneSafe(value) {
  if (typeof structuredClone === "function") return structuredClone(value);
  return JSON.parse(JSON.stringify(value));
}

export function mascotForGame(gameId) {
  return COURSE_CONTENT[gameId]?.mascotId || "ace";
}

function uniqueOptions(values) {
  return Array.from(new Set(values.filter(Boolean)));
}

function seededOptions(correct, distractors, seed) {
  const pool = uniqueOptions([correct, ...distractors]).slice(0, 4);
  while (pool.length < 4) pool.push(`None of these (${pool.length + 1})`);
  const offset = Math.abs(seed) % pool.length;
  return [...pool.slice(offset), ...pool.slice(0, offset)];
}

function stringHash(value) {
  return Array.from(value).reduce((total, char) => ((total * 31) + char.charCodeAt(0)) | 0, 7);
}

export function gameQuiz(gameId) {
  const content = gameContent(gameId);
  if (!content) return [];
  const currentGame = ACADEMY_GAMES.find((game) => game.id === gameId);
  const other = ACADEMY_GAMES.filter((game) => game.id !== gameId).map((game) => gameContent(game.id)).filter(Boolean);
  const seed = stringHash(gameId);
  const firstPhase = content.turnOrder[0];
  const safeStrategy = content.strategy[0];
  const commonMistake = content.commonMistakes[0];
  return [
    { id: `${gameId}-objective`, prompt: `What is the main objective in ${currentGame?.title || "this game"}?`, answer: content.objective, options: seededOptions(content.objective, other.map((item) => item.objective), seed), explanation: content.objective },
    { id: `${gameId}-first-phase`, prompt: "Which phase comes first in this course's basic turn order?", answer: firstPhase, options: seededOptions(firstPhase, [...content.turnOrder.slice(1), ...other.map((item) => item.turnOrder[0])], seed + 1), explanation: `The course starts with “${firstPhase},” then moves through ${content.turnOrder.slice(1).join(", ")}.` },
    { id: `${gameId}-deck`, prompt: "Which deck or card setup does this course use?", answer: content.deckDescription, options: seededOptions(content.deckDescription, other.map((item) => item.deckDescription), seed + 2), explanation: content.deckDescription },
    { id: `${gameId}-strategy`, prompt: "Which choice is a recommended beginner strategy?", answer: safeStrategy, options: seededOptions(safeStrategy, [...content.commonMistakes, ...other.flatMap((item) => item.commonMistakes).slice(0, 4)], seed + 3), explanation: `${safeStrategy} This supports the course objective without changing the rules.` },
    { id: `${gameId}-mistake`, prompt: "Which choice is listed as a common beginner mistake?", answer: commonMistake, options: seededOptions(commonMistake, [...content.strategy, ...other.flatMap((item) => item.strategy).slice(0, 4)], seed + 4), explanation: `${commonMistake} is a common beginner trap in this course.` },
  ];
}

export function guidedDecision(gameId, stepIndex) {
  const content = gameContent(gameId);
  if (!content) return null;
  const step = content.guidedSteps[stepIndex % content.guidedSteps.length];
  const distractors = [step.avoid, ...content.commonMistakes.filter((item) => item !== step.avoid)];
  return {
    prompt: `During “${step.title},” which choice follows the beginner plan?`,
    answer: step.tip,
    options: seededOptions(step.tip, distractors, stringHash(`${gameId}-${stepIndex}`)),
    explanation: `${step.tip} ${step.instruction}`,
  };
}
